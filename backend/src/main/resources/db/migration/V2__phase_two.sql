-- Partial indexes support the two due queues without scanning terminal auctions.
CREATE INDEX auctions_scheduled_start ON auctions(starting_time,id) WHERE status='SCHEDULED';
CREATE INDEX auctions_active_end ON auctions(ending_time,id) WHERE status='ACTIVE';
CREATE INDEX auctions_status_page ON auctions(status,id DESC);
CREATE INDEX bids_auction_rank ON bids(auction_id,amount DESC,id DESC);
CREATE INDEX bids_auction_status ON bids(auction_id,status);
CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE INDEX auctions_name_search ON auctions USING gin(lower(name) gin_trgm_ops);

ALTER TABLE auctions ADD COLUMN lifecycle_claim_token UUID,
  ADD COLUMN lifecycle_claim_until TIMESTAMPTZ,
  ADD COLUMN lifecycle_retry_at TIMESTAMPTZ,
  ADD COLUMN lifecycle_attempts INTEGER NOT NULL DEFAULT 0;

CREATE TABLE auction_outbox (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  auction_id BIGINT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  published_at TIMESTAMPTZ
);
-- No FK: a deletion must still be broadcast after the auction has disappeared.
CREATE INDEX auction_outbox_pending ON auction_outbox(id) WHERE published_at IS NULL;
CREATE INDEX auction_outbox_retention ON auction_outbox(published_at) WHERE published_at IS NOT NULL;

CREATE FUNCTION record_auction_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  -- Ignore worker leases and intermediate bid price reservations. Publish the final
  -- leader update, lifecycle transition, creation or deletion in the same transaction.
  IF TG_OP='UPDATE' THEN
    IF (NEW.status, NEW.winning_bid_id, NEW.final_price) IS NOT DISTINCT FROM
       (OLD.status, OLD.winning_bid_id, OLD.final_price) THEN
      RETURN NEW;
    END IF;
  END IF;
  IF TG_OP='DELETE' THEN
    INSERT INTO auction_outbox(auction_id) VALUES (OLD.id);
    RETURN OLD;
  END IF;
  INSERT INTO auction_outbox(auction_id) VALUES (NEW.id);
  RETURN NEW;
END;
$$;
CREATE TRIGGER auction_change_outbox AFTER INSERT OR UPDATE OR DELETE ON auctions
  FOR EACH ROW EXECUTE FUNCTION record_auction_change();
